for (const [a, b, want] of vectors) {
  test(`rpmvercmp(${JSON.stringify(a)}, ${JSON.stringify(b)}) = ${want}`, () => {
    assert.equal(rpmvercmp(a, b), want);
  });
}

test("tilde sorts before release", () => {
  assert.equal(compareEvr("1.0~rc1-1", "1.0-1"), -1);
  assert.equal(compareEvr("1.0-1", "1.0~rc1-1"), 1);
});

test("epoch dominates version", () => {
  assert.equal(compareEvr("1:1.0-1", "2.0-1"), 1);
  assert.equal(compareEvr("0:1.0-1", "1.0-1"), 0);
});

test("release breaks version ties", () => {
  assert.equal(compareEvr("1.0-1", "1.0-2"), -1);
});

test("parseEvr splits epoch, version, release", () => {
  assert.deepEqual(parseEvr("2:1.2.3-4.avocado"), {
    epoch: 2,
    version: "1.2.3",
    release: "4.avocado",
  });
  assert.deepEqual(parseEvr("1.0"), { epoch: 0, version: "1.0", release: "" });
});
